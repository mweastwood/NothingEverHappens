import 'package:cloud_firestore/cloud_firestore.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';

import 'auth_repository.dart';
import 'family.dart';
import 'family_repository.dart';
import 'firestore_paths.dart';
import 'task_label.dart';

final labelRepositoryProvider = Provider<LabelRepository>((ref) {
  return LabelRepository();
});

final personalLabelsStreamProvider =
    StreamProvider.autoDispose<List<TaskLabel>>((ref) {
      final user = ref.watch(authStateProvider).value;
      if (user == null) return Stream.value(const []);
      final repo = ref.watch(labelRepositoryProvider);
      return repo.watchPersonalLabels(user.uid);
    });

final familyLabelsStreamProvider = StreamProvider.autoDispose<List<TaskLabel>>((
  ref,
) {
  final profile = ref.watch(familyProfileStreamProvider).value;
  final familyId = profile?.familyId ?? '';
  if (familyId.isEmpty) return Stream.value(const []);
  final repo = ref.watch(labelRepositoryProvider);
  return repo.watchFamilyLabels(familyId);
});

final canEditFamilyLabelsProvider = Provider.autoDispose<bool>((ref) {
  final profile = ref.watch(familyProfileStreamProvider).value;
  if (profile == null || profile.familyId.isEmpty) return false;
  return profile.familyRole == FamilyRole.parent.value;
});

final allLabelsMapProvider = Provider.autoDispose<Map<String, TaskLabel>>((
  ref,
) {
  final personal = ref.watch(personalLabelsStreamProvider).value ?? const [];
  final family = ref.watch(familyLabelsStreamProvider).value ?? const [];
  // Precondition: Personal and family labels should have unique IDs generated by
  // Firestore auto-IDs. In the astronomically unlikely event of an ID collision,
  // the family label takes precedence.
  assert(() {
    final personalIds = personal.map((l) => l.id).toSet();
    for (final l in family) {
      if (personalIds.contains(l.id)) {
        return false;
      }
    }
    return true;
  }(), 'Duplicate label ID found across personal and family label sets');
  return {for (final l in personal) l.id: l, for (final l in family) l.id: l};
});

class LabelRepository {
  final FirebaseFirestore _firestore;

  LabelRepository({FirebaseFirestore? firestore})
    : _firestore = firestore ?? FirebaseFirestore.instance;

  Stream<List<TaskLabel>> _watchLabels(
    CollectionReference<TaskLabel> collection,
  ) {
    return collection.snapshots().map(
      (snapshot) =>
          snapshot.docs.map((doc) => doc.data()).toList()..sort((a, b) {
            final orderComparison = a.order.compareTo(b.order);
            if (orderComparison != 0) return orderComparison;
            return a.name.toLowerCase().compareTo(b.name.toLowerCase());
          }),
    );
  }

  Future<void> _reorderLabels(
    CollectionReference<TaskLabel> collection,
    List<TaskLabel> reorderedLabels,
  ) async {
    final batch = _firestore.batch();
    for (var i = 0; i < reorderedLabels.length; i++) {
      final label = reorderedLabels[i];
      if (label.order != i) {
        batch.set(
          collection.doc(label.id),
          label.copyWith(order: i, updatedAt: DateTime.now().toUtc()),
          SetOptions(merge: true),
        );
      }
    }
    await batch.commit();
  }

  Future<void> _saveLabel(
    CollectionReference<TaskLabel> collection,
    TaskLabel label,
  ) async {
    await collection.doc(label.id).set(label, SetOptions(merge: true));
  }

  Future<void> _deleteLabel(
    CollectionReference<TaskLabel> collection,
    String labelId,
  ) async {
    await collection.doc(labelId).delete();
  }

  Stream<List<TaskLabel>> watchPersonalLabels(String userId) {
    if (userId.isEmpty) return Stream.value(const []);
    return _watchLabels(FirestoreCollections.userLabels(_firestore, userId));
  }

  Stream<List<TaskLabel>> watchFamilyLabels(String familyId) {
    if (familyId.isEmpty) return Stream.value(const []);
    return _watchLabels(
      FirestoreCollections.familyLabels(_firestore, familyId),
    );
  }

  Future<void> reorderPersonalLabels(
    String userId,
    List<TaskLabel> reorderedLabels,
  ) => _reorderLabels(
    FirestoreCollections.userLabels(_firestore, userId),
    reorderedLabels,
  );

  Future<void> reorderFamilyLabels(
    String familyId,
    List<TaskLabel> reorderedLabels,
  ) => _reorderLabels(
    FirestoreCollections.familyLabels(_firestore, familyId),
    reorderedLabels,
  );

  Future<void> savePersonalLabel(String userId, TaskLabel label) =>
      _saveLabel(FirestoreCollections.userLabels(_firestore, userId), label);

  Future<void> deletePersonalLabel(String userId, String labelId) =>
      _deleteLabel(
        FirestoreCollections.userLabels(_firestore, userId),
        labelId,
      );

  Future<void> saveFamilyLabel(String familyId, TaskLabel label) => _saveLabel(
    FirestoreCollections.familyLabels(_firestore, familyId),
    label,
  );

  Future<void> deleteFamilyLabel(String familyId, String labelId) =>
      _deleteLabel(
        FirestoreCollections.familyLabels(_firestore, familyId),
        labelId,
      );
}
